    public class WorkspaceEntity
    {
        public string Id { get; private set; } = string.Empty;
        public string Name { get; private set; } = string.Empty;
        public string Description { get; private set; } = string.Empty;
        public string Slug { get; private set; } = string.Empty;
        public WorkspaceType Type { get; private set; }
        public WorkspaceStatus Status { get; private set; }
        public GeoJson Coordinates { get; private set; }
        public double PricePerHour { get; private set; }
        public bool IsInactive { get; private set; }
        public IReadOnlyList<string> Resources { get; private set; } = Array.Empty<string>();
        private List<string> _resources = new List<string>();
        public WorkSpaceAvailability? Availability { get; private set; }
        private WorkSpaceAvailability? _availability;
        public DateTime CreatedAt { get; private set; } = default;
        public DateTime UpdatedAt { get; private set; } = default;
        
        public WorkspaceEntity(
            string name,
            string description,
            WorkspaceType type,
            GeoJson coordinates,
            double pricePerHour,
            IReadOnlyList<string> resources
        )
        {
            this.Id = string.Empty; // Id will be generated by the database upon insertion
            this.Name = NormalizeRequired(name, nameof(name));
            this.Description = NormalizeRequired(description, nameof(description));
            this.Type = ValidateWorkspaceType(type);
            this.Coordinates = ValidateCoordinates(coordinates);
            this.PricePerHour = ValidatePricePerHour(pricePerHour);
            this.Resources = NormalizeResources(resources);
            this._resources = this.Resources.ToList();
            this.CreatedAt = DateTime.UtcNow.ToUniversalTime();
            this.UpdatedAt = DateTime.UtcNow.ToUniversalTime();

            this.Status = WorkspaceStatus.Draft; // Default status
            this.IsInactive = false; // Default to active
        }

        public static WorkspaceEntity Rehydrate(
            string id,
            string name,
            string description,
            string slug,
            WorkspaceType type,
            WorkspaceStatus status,
            GeoJson coordinates,
            double pricePerHour,
            bool isInactive,
            IReadOnlyList<string> resources,
            DateTime createdAt,
            DateTime updatedAt,
            WorkSpaceAvailability? availability
        )
        {
            var entity = new WorkspaceEntity(name, description, type, coordinates, pricePerHour, resources)
            {
                Id = NormalizeId(id),
                Slug = NormalizeRequired(slug, nameof(slug)),
                Status = ValidateWorkspaceStatus(status),
                IsInactive = isInactive,
                CreatedAt = ValidateCreatedAt(createdAt, updatedAt),
                UpdatedAt = ValidateUpdatedAt(updatedAt, createdAt),
                Availability = availability,
                _availability = availability
            };

            return entity;
        }

        public void Publish(string generatedSlug)
        {
            this.Slug = NormalizeRequired(generatedSlug, nameof(generatedSlug));
            this.Status = WorkspaceStatus.Draft; // Set status to Draft when publishing
            this.IsInactive = false;
        }

        public void Activate()
