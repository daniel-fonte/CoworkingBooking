        public void RemoveResource(string resource)
        {
            ArgumentNullException.ThrowIfNullOrWhiteSpace(resource, nameof(resource));

            var trimmedResource = resource.Trim();
            if (_resources.Contains(trimmedResource))
            {
                _resources.Remove(trimmedResource);
                Resources = _resources.AsReadOnly();
            }
        }

        public void AddResource(string resource)
        {
            ArgumentNullException.ThrowIfNullOrWhiteSpace(resource, nameof(resource));

            var trimmedResource = resource.Trim();
            if (!_resources.Contains(trimmedResource))
            {
                _resources.Add(trimmedResource);
                Resources = _resources.AsReadOnly();
            }
        }

