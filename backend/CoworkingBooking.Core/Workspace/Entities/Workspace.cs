        }

        public void MarkAsReserved()
        {
            this.Status = WorkspaceStatus.Reserved;
        }

        public void MarkUnderMaintenance()
        {
            this.Status = WorkspaceStatus.Maintenance;
        }

        public void MarkAsUnavailable()
        {
            this.Status = WorkspaceStatus.Unavailable;
        }

