        private static string NormalizeId(string id)
        {
            ArgumentNullException.ThrowIfNullOrWhiteSpace(id, nameof(id));

            return id.Trim();
        }

        private static string NormalizeRequired(string value, string propertyName)
        {
            return string.IsNullOrWhiteSpace(value)
                ? throw new ArgumentException($"{propertyName} is required.", propertyName)
                : value.Trim();
        }

        private static string NormalizeOptional(string value)
        {
            return string.IsNullOrWhiteSpace(value) ? string.Empty : value.Trim();
        }

        private static DateTime NormalizeDate(DateTime value)
        {
            return value.ToUniversalTime();
        }

        private static WorkspaceType ValidateWorkspaceType(WorkspaceType value)
        {
            return Enum.IsDefined(typeof(WorkspaceType), value)
                ? value
                : throw new ArgumentOutOfRangeException(nameof(value), "Invalid workspace type.");
        }

        private static WorkspaceStatus ValidateWorkspaceStatus(WorkspaceStatus value)
        {
            return Enum.IsDefined(typeof(WorkspaceStatus), value)
                ? value
                : throw new ArgumentOutOfRangeException(nameof(value), "Invalid workspace status.");
        }

        private static GeoJson ValidateCoordinates(GeoJson value)
        {
            ArgumentNullException.ThrowIfNull(value);

            if (value.coordinates is null || value.coordinates.Length != 2)
            {
                throw new ArgumentException("coordinates must contain [longitude, latitude].", nameof(value));
            }

            var longitude = value.coordinates[0];
            var latitude = value.coordinates[1];
            if (longitude is < -180 or > 180 || latitude is < -90 or > 90)
            {
                throw new ArgumentOutOfRangeException(nameof(value), "Invalid longitude/latitude values.");
            }

            return value;
        }

        private static double ValidatePricePerHour(double value)
        {
            return value < 0
                ? throw new ArgumentOutOfRangeException(nameof(value), "pricePerHour cannot be negative.")
                : value;
        }

        private static IReadOnlyList<string> NormalizeResources(IReadOnlyList<string> value)
        {
            ArgumentNullException.ThrowIfNull(value);
            if (value.Any(string.IsNullOrWhiteSpace))
            {
                throw new ArgumentException("resources cannot contain empty items.", nameof(value));
            }

            return value.Select(resource => resource.Trim()).ToList().AsReadOnly();
        }

        private static DateTime ValidateCreatedAt(DateTime createdAt, DateTime updatedAt)
        {
            if (createdAt > updatedAt)
            {
                throw new ArgumentException("createdAt cannot be greater than updatedAt.", nameof(createdAt));
            }

            return NormalizeDate(createdAt);
        }

        private static DateTime ValidateUpdatedAt(DateTime updatedAt, DateTime createdAt)
        {
            if (updatedAt < createdAt)
            {
                throw new ArgumentException("updatedAt cannot be less than createdAt.", nameof(updatedAt));
            }

            return NormalizeDate(updatedAt);
        }

        private static IReadOnlyList<WorkSpaceAvailability> NormalizeAvailabilities(IReadOnlyList<WorkSpaceAvailability> value)
        {
            ArgumentNullException.ThrowIfNull(value);
            return value;
        }
    
